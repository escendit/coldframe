/** Fails unless the reference implementation reproduces every RFC anchor. */
export function verifyAnchors(spec: CryptoSpec): void {
  const failures: string[] = [];
  const expect = (name: string, actual: string, expected: string) => {
    if (actual !== expected) failures.push(`${name}: ${actual} != ${expected}`);
  };
  const h = ANCHORS.rfc5869TestCase1;
  expect('RFC 5869 PRK', hex(hkdfExtract(unhex(h.salt), unhex(h.ikm))), h.prk);
  expect('RFC 5869 OKM', hex(hkdf(unhex(h.salt), unhex(h.ikm), unhex(h.info), h.length)), h.okm);
  const x = ANCHORS.rfc7748Section61;
  expect('RFC 7748 Alice public', hex(x25519PublicKey(unhex(x.alicePrivate))), x.alicePublic);
  expect('RFC 7748 Bob public', hex(x25519PublicKey(unhex(x.bobPrivate))), x.bobPublic);
  expect('RFC 7748 shared (Alice)', hex(x25519(unhex(x.alicePrivate), unhex(x.bobPublic))), x.sharedSecret);
  expect('RFC 7748 shared (Bob)', hex(x25519(unhex(x.bobPrivate), unhex(x.alicePublic))), x.sharedSecret);
  const c = ANCHORS.rfc8439Section282;
  expect('RFC 8439 seal', hex(aeadSeal(unhex(c.key), unhex(c.nonce), unhex(c.aad), unhex(c.plaintext))), c.ciphertext + c.tag);
  expect('RFC 8439 open', hex(aeadOpen(unhex(c.key), unhex(c.nonce), unhex(c.aad), unhex(c.ciphertext + c.tag))), c.plaintext);
  const p = ANCHORS.rfc9180A21;
  const sealed = hpkeSealBase(spec, unhex(p.pkRm), unhex(p.ikmE), unhex(p.info), unhex(p.aad), unhex(p.pt));
  expect('RFC 9180 skEm', hex(sealed.skE), p.skEm);
  expect('RFC 9180 enc', hex(sealed.enc), p.enc);
  expect('RFC 9180 shared_secret', hex(sealed.sharedSecret), p.sharedSecret);
  expect('RFC 9180 key', hex(sealed.key), p.key);
  expect('RFC 9180 base_nonce', hex(sealed.baseNonce), p.baseNonce);
  expect('RFC 9180 ct', hex(sealed.ciphertext), p.ct);
  if (failures.length > 0) {
    throw new Error(`The reference implementation does not reproduce the RFC anchors:\n${failures.join('\n')}`);
  }
}

const ascii = (text: string): Buffer => Buffer.from(text, 'utf8');

function varint(value: bigint): Buffer {
  const bytes: number[] = [];
  let rest = value;
  do {
    const low = Number(rest & 0x7fn);
    rest >>= 7n;
    bytes.push(rest === 0n ? low : low | 0x80);
  } while (rest !== 0n);
  return Buffer.from(bytes);
}

/** `coldframe.device.v1.Downlink` with varint fields 1..3 set, as Protobuf encodes it. */
function encodeDownlink(protocolVersion: number, ackedCounter: bigint, serverTimeMs: bigint): Buffer {
  return Buffer.concat([
    Buffer.from([0x08]),
    varint(BigInt(protocolVersion)),
    Buffer.from([0x10]),
    varint(ackedCounter),
    Buffer.from([0x18]),
    varint(serverTimeMs),
  ]);
}

const ROOT_A = '000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f';
const ROOT_B = 'ffeeddccbbaa998877665544332211000f1e2d3c4b5a69788796a5b4c3d2e1f0';

/** Every vector, in the order vectors.json lists it. */
export function buildVectors(spec: CryptoSpec): Record<string, unknown> {
  verifyAnchors(spec);

  const keyHierarchy = [
    { name: 'counting root', rootKey: ROOT_A },
    { name: 'descending root', rootKey: ROOT_B },
  ].map(({ name, rootKey }) => {
    const keys = deriveDeviceKeys(spec, unhex(rootKey));
    return {
      name,
      rootKey,
      deviceKey: hex(keys.deviceKey),
      sealKey: hex(keys.sealKey),
      ackKey: hex(keys.ackKey),
      hubAuthKey: hex(keys.hubAuthKey),
      deviceId: hex(keys.deviceId),
    };
  });

  const frames = [
    { name: 'first uplink', rootKey: ROOT_A, purpose: 'seal', counter: 0n, plaintext: ascii('coldframe uplink frame') },
    { name: 'uplink with a 5-byte counter', rootKey: ROOT_A, purpose: 'seal', counter: 0x0100000005n, plaintext: ascii('reading 42') },
    { name: 'empty uplink', rootKey: ROOT_B, purpose: 'seal', counter: 18446744073709551614n, plaintext: Buffer.alloc(0) },
    {
      name: 'downlink acknowledging counter 1',
      rootKey: ROOT_A,
      purpose: 'ack',
      counter: 7n,
      plaintext: encodeDownlink(spec.protocolMajor, 1n, 1790000000000n),
    },
  ].map(({ name, rootKey, purpose, counter, plaintext }) => {
    const keys = deriveDeviceKeys(spec, unhex(rootKey));
    const key = purpose === 'seal' ? keys.sealKey : keys.ackKey;
    const nonce = frameNonce(spec, keys.deviceId, counter);
    const aad = frameAad(spec, keys.deviceId, counter);
    return {
      name,
      rootKey,
      purpose,
      key: hex(key),
      deviceId: hex(keys.deviceId),
      counter: counter.toString(),
      plaintext: hex(plaintext),
      nonce: hex(nonce),
      aad: hex(aad),
      ciphertext: hex(aeadSeal(key, nonce, aad, plaintext)),
    };
  });

  const replay = {
    name: 'accepts a counter above the high-water mark or unseen inside the window, once',
    window: spec.frame.replayWindow,
    steps: [
      ['100', true],
      ['100', false],
      ['101', true],
      ['99', true],
      ['99', false],
      ['38', true],
      ['37', false],
      ['200', true],
      ['101', false],
      ['150', true],
      ['150', false],
      ['137', true],
      ['136', false],
      ['201', true],
    ].map(([counter, accepted]) => ({ counter, accepted })),
  };

  const enrolment = [
    {
      name: 'hub enrolment',
      rootKey: ROOT_A,
      recipientPrivateKey: '5f3a1c2b7d9e8f60718293a4b5c6d7e8f90112233445566778899aabbccddeef', // gitleaks:allow (fixed test input)
      ikmE: 'a1a2a3a4a5a6a7a8a9aaabacadaeafb0b1b2b3b4b5b6b7b8b9babbbcbdbebfc0',
    },
    {
      name: 'second device, same server key',
      rootKey: ROOT_B,
      recipientPrivateKey: '5f3a1c2b7d9e8f60718293a4b5c6d7e8f90112233445566778899aabbccddeef', // gitleaks:allow (fixed test input)
      ikmE: '0f0e0d0c0b0a09080706050403020100ffeeddccbbaa99887766554433221100',
    },
  ].map(({ name, rootKey, recipientPrivateKey, ikmE }) => {
    const keys = deriveDeviceKeys(spec, unhex(rootKey));
    const recipientPublicKey = x25519PublicKey(unhex(recipientPrivateKey));
    const sealed = hpkeSealBase(spec, recipientPublicKey, unhex(ikmE), ascii(spec.enrolment.info), keys.deviceId, keys.deviceKey);
    return {
      name,
      rootKey,
      recipientPrivateKey,
      recipientPublicKey: hex(recipientPublicKey),
      fingerprint: fingerprint(recipientPublicKey),
      info: hex(ascii(spec.enrolment.info)),
      ikmE,
      ephemeralPrivateKey: hex(sealed.skE),
      deviceId: hex(keys.deviceId),
      deviceKey: hex(keys.deviceKey),
      enc: hex(sealed.enc),
      sharedSecret: hex(sealed.sharedSecret),
      key: hex(sealed.key),
      baseNonce: hex(sealed.baseNonce),
      ciphertext: hex(sealed.ciphertext),
    };
  });

  const setup = [
    {
      name: 'setup session with a lowercase code',
      popCode: 'k7m2q9xp',
      wrongPopCode: 'K7M2Q9XQ',
      appPrivateKey: '28c1d2e3f405162738495a6b7c8d9eafb0c1d2e3f405162738495a6b7c8d9e6f', // gitleaks:allow (fixed test input)
      hubPrivateKey: '9876543210fedcba9876543210fedcba0123456789abcdef0123456789abcd40', // gitleaks:allow (fixed test input)
      messages: [
        { direction: 'appToHub', counter: 0n, plaintext: ascii('identity please') },
        { direction: 'hubToApp', counter: 0n, plaintext: ascii('identity: hub') },
        { direction: 'appToHub', counter: 1n, plaintext: ascii('wifi scan please') },
      ],
    },
  ].map(({ name, popCode, wrongPopCode, appPrivateKey, hubPrivateKey, messages }) => {
    const appPublic = x25519PublicKey(unhex(appPrivateKey));
    const hubPublic = x25519PublicKey(unhex(hubPrivateKey));
    const app = setupKeys(spec, unhex(appPrivateKey), hubPublic, appPublic, hubPublic, popCode);
    const hub = setupKeys(spec, unhex(hubPrivateKey), appPublic, appPublic, hubPublic, popCode);
    if (!app.appToHubKey.equals(hub.appToHubKey) || !app.hubToAppKey.equals(hub.hubToAppKey)) {
      throw new Error('setup keys differ between app and Hub');
    }
    const aad = setupAad(spec);
    return {
      name,
      popCode,
      normalizedPopCode: popCode.toUpperCase(),
      wrongPopCode,
      appPrivateKey,
      appPublicKey: hex(appPublic),
      hubPrivateKey,
      hubPublicKey: hex(hubPublic),
      sharedSecret: hex(app.sharedSecret),
      appToHubKey: hex(app.appToHubKey),
      hubToAppKey: hex(app.hubToAppKey),
      aad: hex(aad),
      messages: messages.map(({ direction, counter, plaintext }) => {
        const key = direction === 'appToHub' ? app.appToHubKey : app.hubToAppKey;
        const nonce = setupNonce(spec, counter);
        return {
          direction,
          counter: counter.toString(),
          plaintext: hex(plaintext),
          nonce: hex(nonce),
          ciphertext: hex(aeadSeal(key, nonce, aad, plaintext)),
        };
      }),
    };
  });

  const heartbeat = [
    {
      name: 'heartbeat',
      rootKey: ROOT_A,
      method: 'POST',
      path: '/device/heartbeat',
      body: ascii('{"protocolVersion":1,"uptimeMs":61000}'),
      timestampMs: 1790000000000n,
      nonce: '00112233445566778899aabbccddeeff',
    },
    {
      name: 'empty body',
      rootKey: ROOT_B,
      method: 'POST',
      path: '/device/ingest',
      body: Buffer.alloc(0),
      timestampMs: 1790000123456n,
      nonce: 'f0e1d2c3b4a5968778695a4b3c2d1e0f',
    },
  ].map(({ name, rootKey, method, path, body, timestampMs, nonce }) => {
    const keys = deriveDeviceKeys(spec, unhex(rootKey));
    const canonical = heartbeatCanonical(spec, method, path, body, timestampMs, unhex(nonce));
    const signature = hex(hmacSha256(keys.hubAuthKey, ascii(canonical)));
    const { headers } = spec.heartbeat;
    return {
      name,
      rootKey,
      hubAuthKey: hex(keys.hubAuthKey),
      deviceId: hex(keys.deviceId),
      method,
      path,
      body: hex(body),
      timestampMs: timestampMs.toString(),
      nonce,
      bodyHash: hex(sha256(body)),
      canonical,
      signature,
      headers: {
        [headers.device]: hex(keys.deviceId),
        [headers.timestamp]: timestampMs.toString(),
        [headers.nonce]: nonce,
        [headers.signature]: signature,
      },
    };
  });

  return {
    $comment: VECTORS_COMMENT,
    protocolMajor: spec.protocolMajor,
    keyHierarchy,
    frames,
    replay,
    enrolment,
    setup,
    heartbeat,
    anchors: ANCHORS,
  };
}
