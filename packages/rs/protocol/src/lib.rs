pub const SPECIFICATION_SET_MAX_SIZE: usize = max_encoded_size::<device_v1::SpecificationSet>();

// The ciphertext field holds whatever fits one radio payload: an envelope has at least the
// protocol_version (2 bytes), the Device ID (10) and the ciphertext's own header (2).
const _: () = assert!(ENVELOPE_CIPHERTEXT_CAPACITY + 14 >= radio::ENVELOPE_MAX);

// The ciphertext field holds exactly the largest SetupMessage plus its tag.
const _: () = assert!(SEALED_CIPHERTEXT_CAPACITY == SETUP_MESSAGE_MAX_SIZE + SETUP_TAG_LENGTH);

/// Why a message could not be encoded or decoded. Carries no message content.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CodecError {
    /// The output buffer is too small for the encoded message.
    BufferTooSmall,
    /// The bytes are not a valid encoding: truncated, a bad wire type, invalid UTF-8, or a field
    /// over its fixed capacity.
    Malformed,
}

impl fmt::Display for CodecError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::BufferTooSmall => "output buffer too small",
            Self::Malformed => "malformed message",
        })
    }
}

impl core::error::Error for CodecError {}

/// Encodes `message` into the front of `out`; returns the encoded length.
///
/// # Errors
///
/// [`CodecError::BufferTooSmall`] when `out` cannot hold it.
pub fn encode<M: MessageEncode>(message: &M, out: &mut [u8]) -> Result<usize, CodecError> {
    let total = out.len();
    let mut rest: &mut [u8] = out;
    message
        .encode(&mut PbEncoder::new(&mut rest))
        .map_err(|()| CodecError::BufferTooSmall)?;
    Ok(total - rest.len())
}

/// Decodes one message of type `M` from all of `bytes`.
///
/// # Errors
///
/// [`CodecError::Malformed`] when `bytes` is not a valid encoding of `M` within its capacities.
pub fn decode<M: MessageDecode + Default>(bytes: &[u8]) -> Result<M, CodecError> {
    let mut message = M::default();
    message
        .decode_from_bytes(bytes)
        .map_err(|_| CodecError::Malformed)?;
    Ok(message)
}

/// Encodes a `NodeFrame` with its fields in field-number order; returns the encoded length.
///
/// micropb writes a `oneof` after every other field, so [`encode`] would put `measured` (fields
/// 5 and 6) last. Any Protobuf decoder reads both orders alike, but the shared vector of
/// `packages/crypto-spec` pins the bytes other implementations produce, and those are in
/// field-number order. This writes the frame in three parts (fields 1 to 4, `measured`, fields 7
/// to 11), whose concatenation is that encoding.
///
/// # Errors
///
/// [`CodecError::BufferTooSmall`] when `out` cannot hold it.
pub fn encode_node_frame(
    frame: &device_v1::NodeFrame,
    out: &mut [u8],
) -> Result<usize, CodecError> {
    let head = device_v1::NodeFrame {
        protocol_version: frame.protocol_version,
        spec_hash: frame.spec_hash.clone(),
        boot_id: frame.boot_id,
        uptime_ms: frame.uptime_ms,
        ..device_v1::NodeFrame::default()
    };
    let measured = device_v1::NodeFrame {
        measured: frame.measured.clone(),
        ..device_v1::NodeFrame::default()
    };
    let mut tail = frame.clone();
    tail.protocol_version = 0;
    tail.spec_hash.clear();
    tail.boot_id = 0;
    tail.uptime_ms = 0;
    tail.measured = None;

    let mut length = 0;
    for part in [&head, &measured, &tail] {
        let rest = out.get_mut(length..).ok_or(CodecError::BufferTooSmall)?;
        length += encode(part, rest)?;
    }
    Ok(length)
}
