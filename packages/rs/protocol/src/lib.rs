//! Coldframe wire messages, generated from `packages/proto` with micropb (AD-10).
//!
//! `no_std` without `alloc`: every string, bytes and repeated field is a heapless container with
//! a fixed capacity, so each message has a compile-time `MAX_SIZE`.
//!
//! - [`setup_v1`]: the BLE setup protocol, `coldframe.setup.v1` (AD-25). Module path in the
//!   generated code: `coldframe_::setup_::v1_`; the `oneof body` is `SetupMessage_::Body`.
//! - [`device_v1`]: sealed Device frames and downlinks, `coldframe.device.v1` (AD-9, AD-12):
//!   `SealedEnvelope`, `NodeFrame` (its `oneof measured` is `NodeFrame_::Measured`), `Downlink`
//!   and `SpecificationSet`, sized for a Node with four Sensors.
//! - [`radio`]: the Node ⇄ Hub ESP-NOW messages (AD-9): one kind byte, then a fixed body or the
//!   bytes of a `SealedEnvelope`.
//! - [`encode`] and [`decode`]: one message to or from a byte slice; [`encode_node_frame`] for a
//!   `NodeFrame` in field-number order.
//!
//! Types that can hold a Wi-Fi password (`WifiConfig`, `SetupMessage` and its `Body`) do not
//! implement `Debug`, so a password cannot reach a log through `{:?}`.

#![no_std]

use core::fmt;

use micropb::size::max_encoded_size;
use micropb::{MessageDecode, MessageEncode, PbEncoder};

