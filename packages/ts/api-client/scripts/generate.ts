/**
 * Generates `src/schema.ts` from `packages/openapi/coldframe.openapi.json` and `src/live.ts` from
 * `packages/asyncapi/coldframe.asyncapi.json`, both with openapi-typescript.
 * Run `pnpm --filter @coldframe/api-client generate` after changing a contract; a test in
 * `tests/ts/api-client` fails while a committed file is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

export const contractPath = fileURLToPath(new URL('../../../openapi/coldframe.openapi.json', import.meta.url));
export const schemaPath = fileURLToPath(new URL('../src/schema.ts', import.meta.url));

const header = `/* eslint-disable -- generated code keeps openapi-typescript's own style */
/**
 * Generated by openapi-typescript from packages/openapi/coldframe.openapi.json.
 * Do not edit: run \`pnpm --filter @coldframe/api-client generate\`.
 */

`;

/** The schema module for the current contract, as text. */
export async function generateSchema(): Promise<string> {
  const contract: unknown = JSON.parse(readFileSync(contractPath, 'utf8'));
  const ast = await openapiTS(contract as Parameters<typeof openapiTS>[0], { exportType: true });
  return header + astToString(ast);
}

export const liveContractPath = fileURLToPath(new URL('../../../asyncapi/coldframe.asyncapi.json', import.meta.url));
export const livePath = fileURLToPath(new URL('../src/live.ts', import.meta.url));

/** The AsyncAPI channel of the SignalR hub (Story 6.6). */
const liveChannel = 'liveHub';

const liveHeader = `/* eslint-disable -- generated code keeps openapi-typescript's own style */
/**
 * Generated by openapi-typescript from the schemas of packages/asyncapi/coldframe.asyncapi.json.
 * Do not edit: run \`pnpm --filter @coldframe/api-client generate\`.
 */

`;

interface AsyncApiContract {
  readonly info: { readonly title: string; readonly version: string };
  readonly channels: Readonly<Record<string, { readonly address: string; readonly messages: Readonly<Record<string, { readonly $ref: string }>> }>>;
  readonly components: {
    readonly messages: Readonly<Record<string, { readonly name: string; readonly payload: { readonly $ref: string } }>>;
    readonly schemas: Readonly<Record<string, unknown>>;
  };
}

function lastSegment(reference: string): string {
  return reference.slice(reference.lastIndexOf('/') + 1);
}

/**
 * The live module for the current AsyncAPI contract, as text: the contract's schemas as types (AsyncAPI
 * schemas are JSON Schema, so they are handed to openapi-typescript inside an OpenAPI 3.1 document without
 * paths), and the hub's address and message names as constants.
 */
export async function generateLive(): Promise<string> {
  const contract = JSON.parse(readFileSync(liveContractPath, 'utf8')) as AsyncApiContract;
  const document = {
    openapi: '3.1.0',
    info: { title: contract.info.title, version: contract.info.version },
    paths: {},
    components: { schemas: contract.components.schemas },
  };
  const ast = await openapiTS(document as Parameters<typeof openapiTS>[0], { exportType: true });
  const channel = contract.channels[liveChannel];
  if (channel === undefined) {
    throw new Error(`The AsyncAPI contract has no channel ${liveChannel}.`);
  }
  const messages = Object.entries(channel.messages).map(([key, { $ref }]) => {
    const message = contract.components.messages[lastSegment($ref)];
    if (message === undefined) {
      throw new Error(`The AsyncAPI contract has no message ${$ref}.`);
    }
    return { key, name: message.name, schema: lastSegment(message.payload.$ref) };
  });
  const names = messages.map(({ key, name }) => `    ${key}: ${JSON.stringify(name)},`).join('\n');
  const payloads = messages.map(({ name, schema }) => `    ${JSON.stringify(name)}: components["schemas"][${JSON.stringify(schema)}];`).join('\n');
  return `${liveHeader}${astToString(ast)}
/** The path of the SignalR hub, the same on the Server and on the web origin. */
export const liveHubPath = ${JSON.stringify(channel.address)};
/** The hub's message names: the SignalR invocation targets. */
export const liveMessages = {
${names}
} as const;
/** The one argument of each hub message, by its name. */
export type LiveMessagePayloads = {
${payloads}
};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(schemaPath, await generateSchema());
  console.log(`Wrote ${schemaPath}`);
  writeFileSync(livePath, await generateLive());
  console.log(`Wrote ${livePath}`);
}
